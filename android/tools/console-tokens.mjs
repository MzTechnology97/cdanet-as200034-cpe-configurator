#!/usr/bin/env node
/**
 * The colours and measures of the console (console/src/styles/tokens.css) for the Android app:
 * writes ui/ConsoleTokens.kt, which Theme.kt maps onto Material 3. One source for both, so the app
 * looks like the console and follows it when a token changes.
 *
 *   node android/tools/console-tokens.mjs           writes the Kotlin file
 *   node android/tools/console-tokens.mjs --check   fails if the Kotlin file is not up to date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const css = readFileSync(join(root, 'console/src/styles/tokens.css'), 'utf8');
const out = join(root, 'android/app/src/main/java/it/cdanet/cpeconfigurator/ui/ConsoleTokens.kt');

/** The custom properties of the first block that starts with [selector]. */
function block(selector) {
  const i = css.indexOf(`${selector} {`);
  if (i < 0) throw new Error(`tokens.css: ${selector} not found`);
  const body = css.slice(i, css.indexOf('}', i));
  return Object.fromEntries([...body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}
const light = block(':root');
// the dark theme only redefines some tokens: the others are the same as the light one
const dark = { ...light, ...block(":root[data-theme='dark']") };

const COLORS = ['brand', 'brand-ink', 'brand-soft', 'bg', 'surface', 'surface-2', 'surface-3', 'line', 'line-strong', 'ink', 'muted', 'good', 'good-bg', 'warn', 'warn-bg', 'bad', 'bad-bg', 'info', 'info-bg'];
const camel = (n) => n.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const argb = (hex, name) => {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) throw new Error(`tokens.css: --${name} is not a #rrggbb colour (${hex})`);
  return `Color(0xFF${m[1].toUpperCase()})`;
};
const px = (name) => {
  const m = /^(\d+)px$/.exec(light[name] ?? '');
  if (!m) throw new Error(`tokens.css: --${name} is not a px value`);
  return Number(m[1]);
};
const palette = (name, t) => [
  `    /** ${name === 'Light' ? 'Light' : 'Dark'} theme of the console. */`,
  `    val ${name} = ConsolePalette(`,
  ...COLORS.map((c) => `        ${camel(c)} = ${argb(t[c], c)},`),
  '    )',
];

const kt = [
  '// Generated by android/tools/console-tokens.mjs from console/src/styles/tokens.css: do not edit by',
  '// hand. Change the tokens of the console, then run the script (ConsoleTokensTest checks they match).',
  'package it.cdanet.cpeconfigurator.ui',
  '',
  'import androidx.compose.runtime.Immutable',
  'import androidx.compose.ui.graphics.Color',
  '',
  '/** The colours of one theme of the console, by the names of its tokens. */',
  '@Immutable',
  'data class ConsolePalette(',
  ...COLORS.map((c) => `    val ${camel(c)}: Color,`),
  ')',
  '',
  '/** Colours, spacing and radii of the console (dp for the px of the web). */',
  'object ConsoleTokens {',
  ...palette('Light', light),
  ...palette('Dark', dark),
  '',
  '    /** Spacing in steps of 4. */',
  ...['sp-1', 'sp-2', 'sp-3', 'sp-4', 'sp-5', 'sp-6', 'sp-8'].map((n) => `    const val ${n.replace('sp-', 'SPACE_')} = ${px(n)}`),
  '',
  '    /** Corner radii: small controls, cards, large panels. */',
  `    const val RADIUS_SM = ${px('radius-sm')}`,
  `    const val RADIUS = ${px('radius')}`,
  `    const val RADIUS_LG = ${px('radius-lg')}`,
  '}',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const now = readFileSync(out, 'utf8');
  if (now !== kt) {
    console.error('ConsoleTokens.kt is not up to date with console/src/styles/tokens.css: run node android/tools/console-tokens.mjs');
    process.exit(1);
  }
  console.log('ConsoleTokens.kt up to date');
} else {
  writeFileSync(out, kt);
  console.log(`written ${out}`);
}
